import { describe, expect, it } from "vitest";
import { RECITAL_THRESHOLD, recitalRatio } from "../src/lib/util";

const cover = `저는 대학 3학년 때 교내 동아리 일정 관리 서비스를 만드는 팀 프로젝트에서 백엔드 개발을 맡았습니다. 배포 직후 동시 접속자가 늘면서 응답 시간이 3초를 넘는 문제가 발생했고, 원인을 찾기 위해 쿼리 로그를 분석했습니다. 그 결과 일정 목록을 불러올 때마다 사용자별 권한을 반복 조회하는 구조가 문제라는 것을 확인했습니다. 저는 권한 정보를 Redis에 캐싱하고 조회 쿼리를 하나로 합쳐 응답 시간을 0.8초로 줄였습니다. 이 경험을 통해 문제의 원인을 데이터로 확인하고 구조를 개선하는 것이 중요하다는 것을 배웠습니다.
지원 동기는 귀사의 서비스가 수백만 명의 사용자에게 안정적으로 제공되는 과정에 기여하고 싶기 때문입니다. 저는 꾸준히 학습하며 팀과 함께 성장하는 개발자가 되겠습니다.`;

// 외워서 말한 답변을 음성 인식이 받아쓴 모습: 문장부호 없음, 띄어쓰기 차이, 구조→9조, Redis→레디스, 3초→삼 초
const recited = `네 저는 대학 3학년 때 교내 동아리 일정관리 서비스를 만드는 팀 프로젝트에서 백엔드 개발을 맡았습니다 배포 직후 동시 접속자가 늘면서 응답 시간이 삼 초를 넘는 문제가 발생했고 원인을 찾기 위해 쿼리 로그를 분석했습니다 그 결과 일정 목록을 불러올 때마다 사용자 별 권한을 반복 조회하는 9조가 문제라는 것을 확인했습니다 저는 권한 정보를 레디스에 캐싱하고 조회 쿼리를 하나로 합쳐 응답 시간을 0.8초로 줄였습니다 이 경험을 통해 문제의 원인을 데이터로 확인하고 9조를 개선하는 것이 중요하다는 걸 배웠습니다`;

// 앞 절반만 외운 문장, 뒤는 자기 말
const half = `저는 대학 3학년 때 교내 동아리 일정 관리 서비스를 만드는 팀 프로젝트에서 백엔드 개발을 맡았습니다 배포 직후 동시 접속자가 늘면서 응답 시간이 3초를 넘는 문제가 발생했고 원인을 찾기 위해 쿼리 로그를 분석했습니다 근데 사실 처음엔 디비 인덱스 문제인 줄 알고 하루를 날렸는데요 팀원이 권한 조회가 이상하다고 알려줘서 그쪽을 다시 봤고 캐시를 붙이기로 제가 결정했습니다 그때 좀 더 빨리 물어볼 걸 하는 아쉬움이 있습니다`;

// 같은 경험을 자기 말로 풀어 말함
const free = `음 그때 저희가 동아리 일정 앱을 만들었는데요 제가 서버 쪽을 했었습니다 근데 오픈하고 나서 사람들이 몰리니까 화면이 엄청 느리게 뜨더라고요 그래서 로그를 뒤져봤더니 목록 불러올 때 권한 확인을 사람마다 계속 다시 하고 있었어요 그걸 레디스에 넣어두고 쿼리도 한 번만 나가게 바꿨더니 일 초 안쪽으로 들어왔습니다 사실 처음엔 디비 인덱스 문제인 줄 알고 하루를 날렸는데 그게 제일 아쉬웠습니다`;

describe("recitalRatio", () => {
  it("자소서를 외워 말한 답변은 음성 인식 오류가 섞여도 기준을 넘는다", () => {
    expect(recitalRatio(recited, cover)).toBeCloseTo(0.89, 2);
    expect(recitalRatio(half, cover)).toBeCloseTo(0.52, 2);
    expect(recitalRatio(half, cover)).toBeGreaterThanOrEqual(RECITAL_THRESHOLD);
  });

  it("같은 경험을 자기 말로 풀면 기준에 한참 못 미친다", () => {
    expect(recitalRatio(free, cover)).toBeCloseTo(0.03, 2);
    expect(recitalRatio(free, cover)).toBeLessThan(RECITAL_THRESHOLD / 2);
  });

  it("자소서가 없거나 답변이 짧으면 0", () => {
    expect(recitalRatio(recited, "")).toBe(0);
    expect(recitalRatio("백엔드 개발을 맡았습니다.", cover)).toBe(0);
  });
});
